import argparse
import re
import sys
import tomllib
from importlib import metadata
from pathlib import Path

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

ROOT = Path(__file__).resolve().parent.parent
POLICY = tomllib.loads((ROOT / "tools" / "licenses_policy.toml").read_text())
OUTPUT = ROOT / "THIRD_PARTY_NOTICES.md"


def license_of(dist: metadata.Distribution) -> str:
    meta = dist.metadata
    expression = meta.get("License-Expression")
    if expression:
        return expression.strip()
    raw = (meta.get("License") or "").strip()
    if raw and len(raw) < 80 and "\n" not in raw:
        return str(POLICY["aliases"].get(raw, raw))
    for classifier in meta.get_all("Classifier") or []:
        if classifier.startswith("License :: "):
            name = classifier.rsplit("::", 1)[-1].strip()
            return str(POLICY["aliases"].get(name, name))
    return "UNKNOWN"


def closure() -> dict[str, metadata.Distribution]:
    found: dict[str, metadata.Distribution] = {}
    queue = ["saidby"]
    while queue:
        name = canonicalize_name(queue.pop())
        if name in found:
            continue
        try:
            dist = metadata.distribution(name)
        except metadata.PackageNotFoundError:
            continue
        found[name] = dist
        for line in dist.requires or []:
            req = Requirement(line)
            if req.marker is not None and not req.marker.evaluate({"extra": ""}):
                continue
            queue.append(req.name)
    found.pop("saidby", None)
    return found


def reviewed_exception(name: str) -> str | None:
    for key, why in POLICY["exceptions"].items():
        if key == name or (key.endswith("*") and name.startswith(key[:-1])):
            return str(why)
    return None


def is_allowed(spdx: str) -> bool:
    parts = [p for p in re.split(r"\s+(?:AND|OR|WITH)\s+|[()]", spdx) if p.strip()]
    return all(p.strip() in POLICY["allow"] for p in parts)


def audit() -> tuple[list[tuple[str, str, str, str]], list[str]]:
    rows, violations = [], []
    for name, dist in sorted(closure().items()):
        spdx = license_of(dist)
        exception = reviewed_exception(name)
        rows.append((name, dist.version, spdx, exception or ""))
        if exception is None and not is_allowed(spdx):
            violations.append(f"{name} {dist.version}: {spdx}")
    return rows, violations


def render(rows: list[tuple[str, str, str, str]]) -> str:
    lines = [
        "# Third-party notices",
        "",
        "Generated by `tools/third_party_notices.py --write` from the runtime dependency",
        "closure of the environment where it ran. Versions and CUDA wheels vary by platform.",
        "",
        "| Package | Version | License | Reviewed exception |",
        "|---|---|---|---|",
    ]
    lines += [f"| {n} | {v} | {s} | {e} |" for n, v, s, e in rows]
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--write", action="store_true")
    args = parser.parse_args()
    rows, violations = audit()
    if violations:
        print("licenses outside the allow-list:", *violations, sep="\n  ", file=sys.stderr)
        sys.exit(1)
    if args.write:
        OUTPUT.write_text(render(rows))
    print(f"{len(rows)} runtime dependencies, all within policy")


if __name__ == "__main__":
    main()
